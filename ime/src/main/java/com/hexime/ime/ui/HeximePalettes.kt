package com.hexime.ime.ui

/**
 * 配色板 —— 由 tools/extract_palettes.py 从配色 lua 抽出，
 * 图片键面取该 png 的主色（hexime 没有皮肤系统，只用颜色）。改配色跑一遍脚本即可。
 */
data class Palette(
    val id: String,
    val name: String,
    val pageBg: Int,
    val keyboardBg: Int,
    val keyFace: Int,
    val keyText: Int,
    /** 小字/键角长按字符的颜色。 */
    val keySymbol: Int,
    /** 键边框色（浅色几套配色的主要差别就在这）。 */
    val keyBorder: Int,
    val keyPressed: Int,
    val keyPressedText: Int,
    /** 功能键（⌫/⇧/选单…）。 */
    val funcFace: Int,
    val funcText: Int,
    val funcSymbol: Int,
    val funcPressed: Int,
    val funcPressedText: Int,
    /** 回车键。 */
    val enterFace: Int,
    val enterText: Int,
    val enterPressed: Int,
    val enterPressedText: Int,
    /** 空格键。 */
    val spaceFace: Int,
    val spaceText: Int,
    /** 顶栏/状态栏文字。 */
    val statusText: Int,
    val candidateBg: Int,
    val candidateText: Int,
    val candidateComment: Int,
    val candidatePressed: Int,
)

